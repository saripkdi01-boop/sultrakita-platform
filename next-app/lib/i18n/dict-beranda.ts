/** Daftar semua kunci beranda (untuk validasi kelengkapan terjemahan). */
export const BERANDA_KEYS = Object.keys(dictBeranda.id);

/** Interpolasi placeholder {name} {count} {n} {max} {maxMedia} {maxImageMB} {maxVideoMB} {status}. */
export function fmtLabel(template: string, vars: Record<string, string | number> = {}): string {
  let out = template;
  for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}
