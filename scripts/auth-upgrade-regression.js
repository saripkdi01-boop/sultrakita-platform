#!/usr/bin/env node
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const server = read('server.js');
const migration = read('database/migrations/005_auth_channels_google.sql');
const onboardingMigration = read('database/migrations/006_seller_onboarding.sql');
const env = read('.env.example');
const account = read('public/account.html');
const accountJs = read('public/account.js');
const homepage = read('public/index.html');
const serviceWorker = read('public/sw.js');
const theme = read('public/theme.js');
assert.match(migration, /CREATE TABLE IF NOT EXISTS auth_otp_challenges/);
assert.match(migration, /destination_hash TEXT NOT NULL/);
assert.match(migration, /CREATE TABLE IF NOT EXISTS auth_login_exchanges/);
assert.match(migration, /google_sub TEXT/);
assert.match(server, /INSERT INTO auth_otp_challenges/);
assert.match(server, /SELECT id, code_hash, attempts FROM auth_otp_challenges/);
assert.doesNotMatch(server, /INSERT INTO otp_challenges/);
assert.match(server, /EMAIL_PROVIDER.*resend/);
assert.match(server, /RESEND_API_KEY/);
assert.match(server, /GOOGLE_OAUTH_NOT_CONFIGURED/);
assert.match(server, /google_oauth_state=.*HttpOnly; Secure; SameSite=Lax/);
assert.match(server, /auth_login_exchanges/);
assert.match(server, /ALTER TABLE otp_challenges ADD COLUMN IF NOT EXISTS email/);
assert.match(server, /ALTER TABLE users ADD COLUMN IF NOT EXISTS email/);
assert.match(server, /await ensureAuthSchema\(\)/);
assert.match(server, /seller_onboarding_progress/);
assert.match(server, /\/api\/seller\/onboarding\/suggest/);
assert.match(server, /\/api\/seller\/onboarding\/finalize/);
assert.match(account, /\/api\/auth\/google\/start/);
assert.match(accountJs, /google_code/);
assert.match(accountJs, /input\.addEventListener\('input', syncLoginChannel\)/);
assert.match(onboardingMigration, /CREATE TABLE IF NOT EXISTS seller_onboarding_progress/);
assert.match(homepage, /seller-onboarding-dialog/);
assert.match(homepage, /data-onboarding-step="4"/);
assert.match(homepage, /app\.js\?v=seller-onboarding-1/);
assert.match(account, /account\.js\?v=otp-email-2/);
assert.match(serviceWorker, /sultrakita-shell-v6-2/);
assert.match(theme, /localStorage\.setItem\('sultra-dark'/);
for (const file of ['public/index.html', 'public/account.html', 'public/chat.html', 'public/admin.html']) assert.match(read(file), /theme-dark-preload/);
assert.match(env, /EMAIL_PROVIDER=resend/);
assert.match(env, /RESEND_API_KEY=/);
assert.match(env, /GOOGLE_CLIENT_ID=/);
assert.match(env, /GOOGLE_CLIENT_SECRET=/);
console.log('PASS: auth upgrade contracts, migration, provider, OAuth, UI, and theme checks verified');
