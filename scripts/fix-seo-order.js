const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, '..', 'server.js');
let source = fs.readFileSync(file, 'utf8');
const marker = "const escapeXml = value => String(value).replace(/[<>&\\\"']/g, char => ({ '<':'&lt;', '>':'&gt;', '&':'&amp;', '\\\"':'&quot;', \"'\":'&apos;' }[char]));";
const start = source.indexOf(marker);
const end = source.indexOf("app.use((_req, res) => fail(res, 404, 'Endpoint tidak ditemukan'));", start);
const staticMarker = "app.use(express.static(path.join(__dirname, 'public')));";
if (start < 0 || end < 0) throw new Error('SEO route block tidak ditemukan');
const seoBlock = source.slice(start, end);
source = source.slice(0, start) + source.slice(end);
const staticIndex = source.indexOf(staticMarker);
if (staticIndex < 0) throw new Error('Static middleware tidak ditemukan');
source = source.slice(0, staticIndex) + seoBlock + source.slice(staticIndex);
fs.writeFileSync(file, source);
